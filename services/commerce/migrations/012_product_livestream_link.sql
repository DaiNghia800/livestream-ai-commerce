ALTER TABLE products
    ADD COLUMN IF NOT EXISTS livestream_product_id UUID NOT NULL DEFAULT gen_random_uuid();

CREATE UNIQUE INDEX IF NOT EXISTS uq_products_livestream_product_id
    ON products(livestream_product_id);

UPDATE products
SET livestream_product_id = CASE code
    WHEN 'AO01' THEN '11111111-0000-4000-8000-000000000001'::UUID
    WHEN 'DM02' THEN '11111111-0000-4000-8000-000000000002'::UUID
    WHEN 'QJ02' THEN '11111111-0000-4000-8000-000000000003'::UUID
    WHEN 'SM03' THEN '11111111-0000-4000-8000-000000000004'::UUID
    WHEN 'BL04' THEN '11111111-0000-4000-8000-000000000005'::UUID
    WHEN 'PK05' THEN '11111111-0000-4000-8000-000000000006'::UUID
    ELSE livestream_product_id
END
WHERE code IN ('AO01', 'DM02', 'QJ02', 'SM03', 'BL04', 'PK05');
